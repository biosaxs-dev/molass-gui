"""Export a SessionContext as a Jupyter notebook and open it in VS Code.

The "Export to Notebook..." bridge: reproduces the pipeline run in the GUI
so far as a fresh, runnable notebook, so the user can keep going with full
notebook flexibility (re-run with different parameters, compare runs side
by side, etc.) -- see the molass-gui design philosophy note in repo memory
(2026-08-20). Note this is a re-run from scratch, not a live handoff of the
GUI's in-memory state -- "Export", not "Continue", to avoid implying the
notebook resumes execution rather than restarting it.
"""
import os
import shutil
import subprocess
from tkinter import filedialog, messagebox

import nbformat as nbf


def _md(source):
    return nbf.v4.new_markdown_cell(source)


def _code(source):
    return nbf.v4.new_code_cell(source)


def _upgrade_call(model_info, target_var):
    model_key = model_info['model']
    pore_dist = model_info.get('pore_dist')
    ln_pore_sigma = model_info.get('ln_pore_sigma')
    kwargs = ""
    if pore_dist is not None:
        kwargs += f", pore_dist={pore_dist!r}"
    if ln_pore_sigma is not None:
        kwargs += f", model_params={{'ln_pore_sigma': {ln_pore_sigma!r}}}"
    return f"{target_var} = decomp.upgrade({model_key!r}{kwargs})"


def build_notebook(ctx):
    """Build an nbformat notebook reproducing ctx's pipeline so far."""
    cells = [_md(
        "# Molass session -- exported from GUI\n\n"
        "Generated by molass-gui's \"Export to Notebook...\" -- re-runs the same "
        "pipeline from scratch with full notebook flexibility (re-run with "
        "different parameters, compare runs side by side, etc.)."
    )]

    # ctx.uv_pickat mirrors app.py's optional "UV wavelength (nm)" field --
    # None means the GUI's Load dialog was left blank, so omit the kwarg
    # entirely rather than hardcoding the library's own default (280) here.
    uv_pickat_kwarg = "" if ctx.uv_pickat is None else f", uv_pickat={ctx.uv_pickat!r}"

    cells.append(_code(
        "from molass.DataObjects import SecSaxsData as SSD\n\n"
        f"ssd = SSD(r\"{ctx.folder}\"{uv_pickat_kwarg})\n"
        "trimmed = ssd.trimmed_copy()\n"
        "trimmed.plot_compact(baseline=True)"
    ) if ctx.dropbox_path is None else _code(
        # Resolve via Dropbox on every run (cheap no-op when unchanged) rather
        # than baking in the raw local path -- reading that directly would
        # defeat the whole point of sync_dropbox_folder (repeated re-downloads
        # from an "online-only" Dropbox-synced folder). Also more portable: a
        # Dropbox-relative path works on any machine with valid credentials,
        # unlike a machine-specific local mount path.
        "from molass.DataObjects import SecSaxsData as SSD\n"
        "from molass.DataUtils import sync_dropbox_folder\n\n"
        f"data_folder = sync_dropbox_folder(r\"{ctx.dropbox_path}\")\n"
        f"ssd = SSD(data_folder{uv_pickat_kwarg})\n"
        "trimmed = ssd.trimmed_copy()\n"
        "trimmed.plot_compact(baseline=True)"
    ))

    if ctx.num_components is not None:
        proportions = getattr(ctx, 'proportions', None)
        # num_components is redundant (and a footgun if hand-edited out of
        # sync) once proportions is given -- len(proportions) already implies it.
        components_kwarg = (f"proportions={proportions}" if proportions
                            else f"num_components={ctx.num_components}")
        source_kwarg = (f", proportions_source={ctx.proportions_source!r}"
                        if getattr(ctx, 'proportions_source', None) else "")
        ranks_line = (f"decomp.update_xr_ranks({ctx.xr_ranks})\n"
                     if getattr(ctx, 'xr_ranks', None) is not None else "")
        # rgcurve lives in its own cell, computed on `corrected` rather than
        # `decomp` -- retrying quick_decomposition with different
        # num_components/proportions (the most common notebook edit) then
        # only re-runs the cheap decomposition cell below, not the expensive
        # per-frame Guinier fit.
        cells.append(_code(
            "corrected = trimmed.corrected_copy()\n"
            "rgcurve = corrected.get_rg_curve()"
        ))
        cells.append(_code(
            f"decomp = corrected.quick_decomposition({components_kwarg}"
            f"{source_kwarg}, rgcurve=rgcurve)\n"
            f"{ranks_line}"
            "decomp.plot_components(rgcurve=rgcurve)"
        ))

    # active_var tracks the object downstream cells (score, optimize_rigorously)
    # should act on -- the upgraded decomposition when a model upgrade ran,
    # otherwise the plain quick_decomposition result. Kept as a separate
    # variable from `decomp` (rather than overwriting it) so the pre-upgrade
    # EGH decomposition stays available for later comparison in the notebook.
    active_var = "decomp"
    if ctx.model_info is not None and ctx.model_info['model'] != 'egh':
        active_var = f"decomp_{ctx.model_info['model']}"
        cells.append(_code(_upgrade_call(ctx.model_info, active_var)
                          + f"\n{active_var}.plot_components(rgcurve=rgcurve)"))

    if ctx.method is not None:
        cells.append(_code(
            f"score = {active_var}.score(trimmed_ssd=trimmed)\n"
            "score.print_summary()\n"
            "score.plot()"
        ))
        # in_process, async_, monitor, and pipeline_recipe are all deliberately
        # omitted -- they already match the library's own defaults (False, True,
        # True, None), and this is the usual pattern anyway. Both the GUI and the
        # exported notebook now get the same subprocess+auto-recipe behavior "for
        # free" from the library default -- see
        # molass-library/Copilot/refactor/DESIGN_default_in_process_reversal.md.
        # method is always shown, even for 'BH': it incurs zero learning cost
        # (the user already saw/chose BH in the GUI's own combobox), so restating
        # it just makes an already-known fact explicit and reproducible. This
        # differs from in_process/async_/monitor above, which were never GUI-facing
        # choices -- surfacing them would require learning a new concept for no
        # benefit, which is what the "minimal learning cost" rule guards against.
        lines = [
            "# Sibling folder, not the GUI's own analysis_folder -- reusing that path",
            "# exactly can collide with the GUI's own run still using it (optimize_rigorously",
            "# would just reconnect to it instead of starting a fresh monitored run).",
            f'analysis_folder = r"{ctx.analysis_folder}_notebook"',
        ]
        num_jobs = getattr(ctx, 'num_jobs', None)
        # Honestly re-express the GUI's auto_constraint=False decision as an
        # explicit constraints=[] here -- pipeline_recipe itself is deliberately
        # never shown (see the comment block above), so this is the only way
        # the exported script wouldn't silently pick up the library's own
        # default auto-applied LumpingConstraint, which the equal-split
        # fallback proportions (not a user choice) shouldn't seed.
        constraints_kwarg = ([] if not getattr(ctx, 'trust_proportions', True) else None)
        if num_jobs and num_jobs > 1:
            # Successive-jobs pattern (molass-researcher experiment 36): each
            # round reseeds init_params from the best params found so far.
            # num_jobs requires async_=False -- the call blocks until every
            # round completes (see optimize_rigorously docs).
            lines += [
                f"run_info = {active_var}.optimize_rigorously(",
                "    trimmed_ssd=trimmed,",
                f"    method={ctx.method.upper()!r},",
                "    analysis_folder=analysis_folder,",
                f"    num_jobs={num_jobs},",
                "    async_=False,",
            ]
            if constraints_kwarg is not None:
                lines.append("    constraints=[],  # equal-split fallback proportions -- not user-vouched-for")
            lines.append(")")
        else:
            lines += [
                f"run_info = {active_var}.optimize_rigorously(",
                "    trimmed_ssd=trimmed,",
                f"    method={ctx.method.upper()!r},",
                "    analysis_folder=analysis_folder,",
            ]
            if constraints_kwarg is not None:
                lines.append("    constraints=[],  # equal-split fallback proportions -- not user-vouched-for")
            lines.append(")")
        cells.append(_code("\n".join(lines)))
        cells.append(_code("run_info.live_status()"))

    nb = nbf.v4.new_notebook()
    nb['cells'] = cells
    return nb


def _open_in_vscode(path):
    for exe in ("code-insiders", "code"):
        found = shutil.which(exe)
        if found:
            subprocess.Popen([found, path])
            return True
    return False


def build_restore_notebook(analysis_folder):
    """Build an nbformat notebook that reconnects to an existing analysis_folder.

    Unlike build_notebook() (which re-runs the whole GUI pipeline from
    scratch), this is the "Open Existing Analysis" / result_mode counterpart:
    it reconnects to a run that may already be finished. The notebook checks
    the run's live phase and branches: if the GUI (or anything else) still has
    an optimization running against this analysis_folder, this starts a fresh
    optimization of its own into a sibling "_notebook" folder -- same
    collision-avoidance pattern as build_notebook() -- instead of reusing the
    GUI's own path, which optimize_rigorously() would just silently reconnect
    to; if it's idle, this uses RunInfo.restore() + load_best() to show the
    best completed result, both as a score summary and as a components plot
    (molass-library#290 -- restore()+load_best() is the single correct,
    tested path to a plottable Decomposition here; plotting the bare `decomp`
    from the cell above would silently show the pre-optimization state, since
    it is never updated with the optimized parameters).
    """
    cells = [_md(
        "# Molass session -- restored from GUI\n\n"
        "Generated by molass-gui's \"Export to Notebook...\" from an existing "
        "analysis. If the optimization is still running (in the GUI or "
        "elsewhere), this runs its own optimization into a sibling folder; "
        "if it's idle, this shows the best completed result's score and "
        "a components plot."
    )]

    cells.append(_code(
        "from molass.Rigorous.RecipeRunner import rebuild_decomposition_from_recipe\n"
        "from molass.Rigorous.RunInfo import RunInfo, restore\n"
        "from molass.Rigorous.CurrentStateUtils import try_fast_rg_curve\n\n"
        f"analysis_folder = r\"{analysis_folder}\"\n"
        "ssd, trimmed, decomp, recipe = rebuild_decomposition_from_recipe(analysis_folder)\n"
        "# Reloads the Rg curve this analysis already exported, instead of\n"
        "# repeating the one-Guinier-fit-per-frame computation.\n"
        "if not try_fast_rg_curve(decomp, analysis_folder):\n"
        "    decomp.get_rg_curve()\n"
        "rgcurve = decomp.get_rg_curve()  # already computed/cached above"
    ))

    cells.append(_code(
        "run_info = RunInfo.reconnect(analysis_folder, raise_if_not_found=False)\n"
        "phase = run_info.live_status()['phase'] if run_info is not None else 'completed'\n"
        "print(f\"phase: {phase}\")\n"
        "\n"
        "if phase == 'running':\n"
        "    # Sibling folder, not the GUI's own analysis_folder -- reusing that path\n"
        "    # exactly would make optimize_rigorously() silently reconnect to (and thus\n"
        "    # share job history with) the GUI's still-running optimizer.\n"
        "    notebook_analysis_folder = analysis_folder + \"_notebook\"\n"
        "    run_info = decomp.optimize_rigorously(\n"
        "        trimmed_ssd=trimmed,\n"
        "        method=recipe.get('method', 'bh').upper(),\n"
        "        analysis_folder=notebook_analysis_folder,\n"
        "    )\n"
        "    run_info.live_status()\n"
        "else:\n"
        "    # restore() attaches decomp to a fresh RunInfo so load_best() can\n"
        "    # rebuild a Decomposition from the best completed job on disk --\n"
        "    # the bare `decomp` above stays at its pre-optimization state and\n"
        "    # should not be plotted directly.\n"
        "    run_info = restore(decomp, analysis_folder, rgcurve=rgcurve)\n"
        "    result = run_info.load_best()\n"
        "    print(f\"SV = {result.sv:.2f}  (fv = {result.fv:.4f})\")\n"
        "    result.plot_components(rgcurve=rgcurve)"
    ))

    nb = nbf.v4.new_notebook()
    nb['cells'] = cells
    return nb


def _ask_path_write_and_open(nb, default_name, parent_win):
    """Ask for a save path, write nb, open it in VS Code.

    Shared tail end of export_and_open()/export_restore_and_open(). Failures
    are shown as a messagebox rather than raised -- this is a convenience
    bridge, not a critical path; the GUI session keeps working regardless of
    the outcome.
    """
    path = filedialog.asksaveasfilename(
        title="Save notebook as",
        defaultextension=".ipynb",
        filetypes=[("Jupyter Notebook", "*.ipynb")],
        initialfile=default_name,
        parent=parent_win,
    )
    if not path:
        return

    overwriting_existing = os.path.exists(path)

    try:
        nbf.write(nb, path)
    except Exception as exc:
        messagebox.showerror("Export failed", str(exc), parent=parent_win)
        return

    if not _open_in_vscode(path):
        messagebox.showinfo(
            "Notebook saved",
            f"Saved to:\n{path}\n\n(VS Code CLI not found on PATH -- open it manually.)",
            parent=parent_win,
        )
    elif overwriting_existing:
        messagebox.showinfo(
            "Notebook updated",
            "If this notebook was already open in VS Code, its tab may not "
            "auto-refresh -- close and reopen the tab to see the update.",
            parent=parent_win,
        )


def export_and_open(ctx, parent_win):
    """Ask for a save path, write the notebook, open it in VS Code."""
    from datetime import datetime
    # Timestamped default name -- a reused fixed name (e.g. molass_session.ipynb)
    # would silently reopen an already-open stale tab: VS Code's notebook editor
    # does not reliably auto-reload an open .ipynb when it changes on disk
    # externally, so re-exporting to the same path can appear to "not work"
    # even though the file itself was written correctly (see repo memory).
    default_name = f"molass_session_{datetime.now():%Y%m%d_%H%M%S}.ipynb"
    try:
        nb = build_notebook(ctx)
    except Exception as exc:
        messagebox.showerror("Export failed", str(exc), parent=parent_win)
        return
    _ask_path_write_and_open(nb, default_name, parent_win)


def export_restore_and_open(analysis_folder, parent_win):
    """Ask for a save path, write the restore notebook, open it in VS Code."""
    from datetime import datetime
    default_name = f"molass_restore_{datetime.now():%Y%m%d_%H%M%S}.ipynb"
    try:
        nb = build_restore_notebook(analysis_folder)
    except Exception as exc:
        messagebox.showerror("Export failed", str(exc), parent=parent_win)
        return
    _ask_path_write_and_open(nb, default_name, parent_win)
